    <script>
        const JAWABAN_BENAR = {
            q1:'B', q2:'A', q3:'D', q4:'A', q5:'C',
            q6:'B', q7:'D', q8:'B', q9:'A', q10:'C'
        };

        function submitKuis() {
            let skor = 0;
            for (let i = 1; i <= 10; i++) {
                const nama    = 'q' + i;
                const benar   = JAWABAN_BENAR[nama];
                const dipilih = document.querySelector(`input[name="${nama}"]:checked`);
                document.querySelectorAll(`input[name="${nama}"]`).forEach(input => {
                    const label = input.closest('.pilihan');
                    if (input.value === benar) label.classList.add('benar');
                    if (dipilih && input.value === dipilih.value && dipilih.value !== benar) label.classList.add('salah');
                    input.disabled = true;
                });
                if (dipilih && dipilih.value === benar) skor++;
            }
            tampilkanModal(skor);
        }

        function tampilkanModal(skor) {
            document.getElementById('modalSkor').textContent = skor + ' / 10';
            const data = skor === 10
                ? ['🏆','Sempurna!','Kamu benar-benar mengenal OrangUtan Haven!']
                : skor >= 7
                ? ['🎉','Bagus Sekali!','Hampir sempurna! Cek jawaban yang ditandai merah ya.']
                : skor >= 4
                ? ['📚','Lumayan!','Masih perlu belajar lebih banyak tentang penghuni Haven.']
                : ['🦧','Terus Semangat!','Yuk pelajari lagi kisah orang utan Haven!'];
            document.getElementById('modalEmoji').textContent = data[0];
            document.getElementById('modalJudul').textContent = data[1];
            document.getElementById('modalPesan').textContent = data[2];
            document.getElementById('modalOverlay').classList.add('tampil');
        }

        function ulangiKuis() {
            document.querySelectorAll('input[type="radio"]').forEach(input => {
                input.checked  = false;
                input.disabled = false;
                input.closest('.pilihan').classList.remove('benar','salah');
            });
            document.getElementById('modalOverlay').classList.remove('tampil');
            window.scrollTo({ top:0, behavior:'smooth' });
        }
    </script>

